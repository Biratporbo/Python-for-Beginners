# Examples of Arithmetic Operator
a = 10
b = 9
c = 0

c = a + b
print("a: {} b: {} a+b {}".format(a,b,c))

c = a * b
print("a: {} b: {} a*b {}".format(a,b,c))

c = a - b
print("a: {} b: {} a-b {}".format(a,b,c))

c = a/b
print("a: {} b: {} a/b: {}".format(a,b,c))

c = a % b
print("a: {} b: {} a%b: {}".format(a,b,c))

a = 9
b = 2
c = a**b
print("a: {} b: {} a**b: {}".format(a,b,c))

a = 10
b = 5
c = a//b 
print ("a: {} b: {} a//b: {}".format(a,b,c))